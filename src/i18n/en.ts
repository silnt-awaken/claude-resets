/**
 * Widen string literals to `string` recursively while keeping every key and every
 * tuple length. `typeof en` alone would demand the exact English strings, so no
 * translation could ever satisfy it.
 */
type Widen<T> = T extends string
  ? string
  : T extends readonly unknown[]
    ? { readonly [K in keyof T]: Widen<T[K]> }
    : T extends object
      ? { readonly [K in keyof T]: Widen<T[K]> }
      : T;

export type Dict = Widen<typeof en>;
